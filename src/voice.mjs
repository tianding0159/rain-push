// 种子 = 日期 + 推送轮次(+手动时的随机盐)
// 为什么不每次纯随机：早上那条会被中午复查「更新」（同一个通知 id），
// 若每次都换，同一条通知的措辞会莫名跳变。所以定时的两趟各自固定、彼此不同；
// 手动触发（测试用）才每次都换。
// 注：Cloudflare Workers 是支持 Math.random / Date.now 的（Date.now 不在执行期推进），
// 早先注释里写「Worker 无 Math.random」是错的，已纠正。
function seed(day, salt = 0, variant = '') {
  let h = salt >>> 0;
  for (const ch of (day + '|' + variant)) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h;
}
const pick = (a, s) => a[s % a.length];

export function rainShape(hit) {
  if (!hit || hit.length < 2) return 'brief';
  const hs = hit.map(h => h[0]).sort((a, b) => a - b);
  const span = hs[hs.length - 1] - hs[0] + 1;
  if (span - hs.length >= 2) return 'onoff';
  if (span >= 6) return 'long';
  if (span <= 2) return 'brief';
  return null;
}
export function compose(r, day, sites, CFG, opts = {}) {
  const p = n => String(n).padStart(2, '0');
  // manual 用随机盐 → 每次手动触发文案都不同，方便看效果
  const variant = opts.slot === 'manual'
    ? 'm' + Math.floor(Math.random() * 1e9).toString(36)
    : (opts.slot || 'morning');
  const tier = r.maxMm >= 8 ? 'torrent'
             : (r.maxMm >= 3 || r.thunder) ? 'heavy'
             : r.maxMm >= 1 ? 'moderate' : 'drizzle';
  const m = MOOD[tier];
  const key = r.hitAmRush && r.hitPmRush ? 'both'
            : r.hitPmRush ? 'pm' : r.hitAmRush ? 'am' : 'none';
  const lines = [];
  if (opts.noon) lines.push(pick(NOON, seed(day, 31, variant)));
  lines.push(`${pick(COMMUTE[key], seed(day, 0, variant))} ${pick(m.faces, seed(day, 7, variant))}`);
  if (r.thunder) lines.push(pick(THUNDER, seed(day, 19, variant)));
  // 短时雨撞通勤 → 换用不冲突的那组
  let shapeKey = opts.shape;
  if (shapeKey === 'brief' && (r.hitAmRush || r.hitPmRush)) shapeKey = 'briefCommute';
  if (shapeKey && SHAPE[shapeKey]) lines.push(pick(SHAPE[shapeKey], seed(day, 23, variant)));
  const differs = sites.length > 1 && sites.some(x => x.spark !== sites[0].spark);
  for (const x of (differs ? sites : [sites[0]])) {
    if (differs && x.totalMm < CFG.siteQuietMm) lines.push(`${x.name}那边基本没有～`);
    else lines.push(`${differs ? x.name + ' ' : ''}${p(r.start)} ${x.spark} ${p(r.end)}  ${x.totalMm.toFixed(1)}mm`);
  }
  lines.push(pick(m.tails, seed(day, 13, variant)));
  return {
    title: `豆豆，今天有雨哦♡ ${p(r.start)}:00–${p(r.end)}:00`,
    subtitle: `${r.grade}，最大 ${r.maxMm.toFixed(1)}mm/h（${p(r.peakHour)} 点前后）`,
    body: lines.join('\n'),
  };
}
